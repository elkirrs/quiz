export function translate(key, language = locale.value) {
  return language === 'ru' ? (ru[key] ?? key) : key
}

export function localizeMessage(message, language = locale.value) {
  if (!message) return message
  for (const [english, russian] of Object.entries(ru)) {
    if (message === english || message === russian) return translate(english, language)
    if ((english.endsWith(':') || english.endsWith('.')) &&
        (message.startsWith(english + ' ') || message.startsWith(russian + ' '))) {
      const source = message.startsWith(english + ' ') ? english : russian
      return translate(english, language) + message.slice(source.length)
    }
  }
  return message
}
